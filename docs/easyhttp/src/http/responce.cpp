#include <http/response.hpp>
#include <http/status.h>

#include <cctype>
#include <algorithm>
#include <charconv>

HttpResponse::HttpResponse() {
    http_version = "HTTP/1.1";
    status = http_status_str(HTTP_CODE_INTERNAL_SERVER_ERROR);
    status_int = HTTP_CODE_INTERNAL_SERVER_ERROR;
}

void HttpResponse::setHttpVersion(std::string version) {
    if (version != "HTTP/1.1" && version != "HTTP/1.0") { return; }

    http_version = version;
}

void HttpResponse::setStatus(int code) {
    const char *status_check_str = http_status_str(code);
    if (!status_check_str) { return; }
    status = status_check_str;
    status_int = code;
}

void HttpResponse::addHeader(std::string name, std::string value) {
    if (name.empty()
        || name.find_first_of(std::string_view(":\r\n \t\0", 6)) != std::string::npos
        || value.find_first_of(std::string_view("\r\n\0", 3)) != std::string::npos) { return; }

    std::string lower_name = name;
    std::transform(lower_name.begin(), lower_name.end(), lower_name.begin(),
                   [](unsigned char c) { return std::tolower(c); });

    // framing headers are generated by encode()
    if (lower_name == "content-length" || lower_name == "transfer-encoding") { return; }

    http_header_t hdr;
    hdr.name = name; hdr.value = value;
    headers.push_back(hdr);
}

void HttpResponse::setBody(std::string bod) {
    body = std::move(bod);
}

void HttpResponse::encode() {
    response.clear();
    response += (http_version + " " + status + "\r\n");

    for (unsigned int i = 0; i < headers.size(); i++) {
        response += (headers[i].name + ": " + headers[i].value + "\r\n");
    }

    // 1xx, 204 and 304 must not carry Content-Length
    if (status_int >= 200 && status_int != 204 && status_int != 304) {
        response += ("Content-Length: " + std::to_string(body.size()) + "\r\n");
    }

    response += "\r\n";
    response += body;
}

