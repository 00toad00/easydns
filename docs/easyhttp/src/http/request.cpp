#include <http/request.hpp>

#include <cctype>
#include <algorithm>
#include <charconv>

HttpRequest::HttpRequest() {
    method = "GET";
    request_target = "/";
    http_version = "HTTP/1.1";
}

void HttpRequest::setMethod(std::string mthd) {
    if (mthd.empty() || mthd.find_first_of(std::string_view(":\r\n \t\0", 6)) != std::string::npos) { return; }

    method = mthd;
}

void HttpRequest::setRequestTarget(std::string target) {
    if (target.empty() || target.find_first_of(std::string_view(" \t\r\n\0", 5)) != std::string::npos) { return; }

    request_target = target;
}

void HttpRequest::setHttpVersion(std::string version) {
    if (version != "HTTP/1.1" && version != "HTTP/1.0") { return; }

    http_version = version;
}

void HttpRequest::addHeader(std::string name, std::string value) {
    if (name.empty()
        || name.find_first_of(std::string_view(":\r\n \t\0", 6)) != std::string::npos
        || value.find_first_of(std::string_view("\r\n\0", 3)) != std::string::npos) { return; }

    std::string lower_name = name;
    std::transform(lower_name.begin(), lower_name.end(), lower_name.begin(),
                   [](unsigned char c) { return std::tolower(c); });

    // framing headers are generated by encode()
    if (lower_name == "content-length" || lower_name == "transfer-encoding") { return; }

    http_header_t hdr;
    hdr.name = name; hdr.value = value;
    headers.push_back(hdr);
}

void HttpRequest::setBody(std::string bod) {
    body = std::move(bod);
}

void HttpRequest::encode() {
    request.clear();

    request += (method + " " + request_target + " " + http_version + "\r\n");

    for (unsigned int i = 0; i < headers.size(); i++) {
        request += (headers[i].name + ": " + headers[i].value + "\r\n");
    }

    if (!body.empty()) { request += ("Content-Length: " + std::to_string(body.size()) + "\r\n"); }

    request += "\r\n";
    request += body;
}

